$edid = Get-Edid -brand $Brand
Write-Host "[spoof-monitor] brand=$Brand  EDID size=$($edid.Length) bytes" -Fore Cyan

# Find every monitor under DISPLAY\* and overwrite its EDID. There's
# usually only one (the vGPU virtual monitor).
$base = 'HKLM:\SYSTEM\CurrentControlSet\Enum\DISPLAY'
Get-ChildItem $base -EA 0 | ForEach-Object {
    $devKey = $_  # e.g. NVD0000
    Get-ChildItem $devKey.PSPath -EA 0 | ForEach-Object {
        $instKey = $_
        $param = Join-Path $instKey.PSPath 'Device Parameters'
        if (Test-Path $param) {
            try {
                Set-ItemProperty -Path $param -Name 'EDID' -Value $edid -Type Binary -Force
                Write-Host "  patched $param"
            } catch {
                Write-Host "  FAILED $param : $_" -Fore Yellow
            }
        }
    }
}

# Windows caches the parsed monitor name from the FIRST EDID it ever
# saw on this device instance. Just rewriting the registry value
# isn't enough; we need to disable + re-enable the monitor device
# so the kernel calls back into the EDID parser.
Write-Host '[spoof-monitor] cycling monitor device for EDID re-parse' -Fore Cyan
$active = Get-PnpDevice -Class Monitor -PresentOnly | Select-Object -First 1
if ($active) {
    Write-Host "  cycling $($active.InstanceId)"
    Disable-PnpDevice -InstanceId $active.InstanceId -Confirm:$false -EA SilentlyContinue
    Start-Sleep -Milliseconds 500
    Enable-PnpDevice  -InstanceId $active.InstanceId -Confirm:$false -EA SilentlyContinue
}
& pnputil.exe /scan-devices 2>&1 | Out-Null
Start-Sleep 2

# Some EDID + driver combinations refuse to update the FriendlyName
# even after a cycle. Belt+suspenders: rewrite the DeviceDesc string
# under the active monitor's PnP enum key directly. The brand string
# we want is encoded in the EDID (for inspectors) AND visible in
# Device Manager (for the user).
$brandLabel = switch ($Brand) {
    'dell-p2419h'    { 'DELL P2419H' }
    'samsung-s24f350'{ 'SAMSUNG S24F350' }
    'lg-27uk850'     { 'LG UltraFine 27UK850' }
    default          { 'Generic Monitor' }
}
$active = Get-PnpDevice -Class Monitor -PresentOnly | Select-Object -First 1
if ($active) {
    $regKey = "HKLM:\SYSTEM\CurrentControlSet\Enum\$($active.InstanceId)"
    if (Test-Path $regKey) {
        $cur = (Get-ItemProperty -Path $regKey -Name DeviceDesc -EA 0).DeviceDesc
        # DeviceDesc may be "@monitor.inf,%foo%;Generic PnP Monitor"
        # or just plain text. Replace the trailing component.
        if ($cur -match '^@.+;(.+)$') {
            $new = ($cur -replace ';.+$', ";$brandLabel")
        } else {
            $new = $brandLabel
        }
        Set-ItemProperty -Path $regKey -Name DeviceDesc -Value $new -Force
        Write-Host "  DeviceDesc -> $new"
    }
}

