<#
.SYNOPSIS
  Monitor EDID spoof — make Windows think the vGPU's virtual display
  is a real-world brand-name monitor (default: Dell P2419H 24" 1080p).

.WHY NOT IddSampleDriver
  IddSampleDriver registers an entirely separate display ADAPTER and
  monitor as "Microsoft Indirect Display". That fights our "single
  GPU + single monitor" goal — Device Manager would show two of each.
  Cleaner approach: keep the existing vGPU monitor entry, just rewrite
  the EDID block in the registry. Windows re-parses it on the next
  PnP enumeration; the friendly name comes straight from the EDID
  manufacturer code + product code.

.HOW
  HKLM\SYSTEM\CurrentControlSet\Enum\DISPLAY\<dev>\<inst>\Device
  Parameters\EDID is a 128- or 256-byte binary blob. Overwrite it
  with a known-good blob from a Dell / Samsung / LG monitor and
  trigger a PnP rescan. Windows then identifies the monitor by the
  EDID's manufacturer ID + product code, looks it up in its built-in
  monitor INF database, and renders the friendly name accordingly.

.PARAMETER Brand
  dell-p2419h | samsung-s24f350 | lg-27uk850

.NOTES
  - The EDID blob is normally write-locked by the kernel after first
    PnP enum. We use Set-ItemProperty (admin) which goes through
    Win32 RegSetValueExW; this generally works on Windows 10 even on
    locked vendor keys.
  - vGPU's monitor InstanceId starts with DISPLAY\NVD0000\... Once
    the new EDID is parsed Windows may re-enumerate the device under
    a different prefix (e.g. DISPLAY\DELA0E2\...). That's fine.
#>
[CmdletBinding()]
param(
    [ValidateSet('dell-p2419h','samsung-s24f350','lg-27uk850','generic-1080p')]
    [string]$Brand = 'dell-p2419h'
)

if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
